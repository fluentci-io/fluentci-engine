import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def edn(value):
    if value is None:
        return "nil"
    if isinstance(value, dict):
        return "{" + " ".join(edn(k) + " " + edn(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + " ".join(map(edn, value)) + "]"
    return json.dumps(value, ensure_ascii=False)


def type_of(spec):
    if "$ref" in spec:
        result = spec["$ref"].rsplit("/", 1)[1]
    elif spec.get("type") == "array":
        result = "(t/Vec " + type_of(spec["items"]) + ")"
    else:
        result = {"string": "t/Str", "boolean": "t/Bool", "integer": "t/Int",
                  "buffer": "(t/Vec (t/HVec [t/Str t/Str]))"}[spec["type"]]
    return f"(t/Option {result})" if spec.get("nullable") else result


