"""Generate Rust PDK imports and per-example XTP schemas from the canonical IDL."""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schema"

def rust_type(parameter):
    if parameter.get("contentType", "").startswith("text/plain"):
        assert parameter["type"] == "string"
        return "String"
    if parameter.get("type") == "buffer":
        # Legacy environment pairs are JSON bytes; XTP v1 has no nested tuple arrays.
        return "Json<Vec<(String, String)>>"
    assert parameter["contentType"] == "application/json"
    if parameter.get("type") == "boolean":
        return "Json<bool>"
    if parameter.get("type") == "array":
        item = parameter["items"]
        if item.get("type") == "string": return "Json<Vec<String>>"
        if item.get("type") == "integer": return "Json<Vec<u32>>"
        if item.get("type") == "array": return "Json<Vec<(String, String)>>"
        if item.get("$ref") == "#/components/schemas/Secret": return "Json<Vec<types::Secret>>"
        raise ValueError(f"Unsupported array: {parameter}")
    name = parameter["$ref"].removeprefix("#/components/schemas/")
    payload = {"StringList": "Vec<String>", "Environment": "Vec<(String, String)>",
               "UInt32List": "Vec<u32>", "SecretList": "Vec<types::Secret>"}.get(name, name)
    return f"Json<{payload}>"

def generated():
    schema = json.loads((SCHEMA / "host.json").read_text())
    modules = json.loads((SCHEMA / "pdk-modules.json").read_text())
    plugins = json.loads((SCHEMA / "plugins.json").read_text())
    for module, names in modules.items():
        lines = ['// Generated by scripts/xtp_codegen.py from schema/host.json. Do not edit.',
                 '#[host_fn]', 'extern "ExtismHost" {']
        for name in names:
            function = schema["imports"][name]
            argument = f"input: {rust_type(function['input'])}" if 'input' in function else ''
            result = f" -> {rust_type(function['output'])}" if 'output' in function else ''
            lines.append(f"    fn {name}({argument}){result};")
        lines.extend(['}', ''])
        yield ROOT / f"crates/pdk/src/generated/{module}_imports.rs", '\n'.join(lines)
    # Python's compiler discovers imports in the entry AST. The SDK build command
    # inlines these guest declarations and preserves void ABI signatures.
    python = ['# Generated from schema/host.json. Guest declarations, not a host runtime.', 'import extism', '']
    typing = []
    for name, function in schema['imports'].items():
        argument = 'value: str' if 'input' in function else ''
        result = ' -> str' if 'output' in function else ''
        python.extend([f'@extism.import_fn("extism:host/user", "{name}")',
                       f'def {name}({argument}){result}:',
                       '    raise RuntimeError("Compile this plugin with fluentci-plugin; these are guest imports")', ''])
        typing.append(f'def {name}({argument}) -> {"str" if "output" in function else "None"}: ...')
    yield ROOT / 'sdk/python/src/fluentci/_imports.py', '\n'.join(python)
    yield ROOT / 'sdk/python/src/fluentci/_imports.pyi', '\n'.join(typing) + '\n'
    javascript = ['// Generated from schema/host.json. Guest import signatures.',
                  'declare module "main" { export function greet(): I32; }',
                  'declare module "extism:host" { interface user {']
    for name, function in schema['imports'].items():
        argument = 'value: I64' if 'input' in function else ''
        result = 'I64' if 'output' in function else 'void'
        javascript.append(f'  {name}({argument}): {result};')
    javascript.extend(['} }', ''])
    for language in ['gleam', 'purescript', 'rescript', 'typescript']:
        yield ROOT / f'sdk/{language}/demo-plugin/imports.d.ts', '\n'.join(javascript)
    for name, exports in plugins.items():
        if name != 'xtp-smoke':
            source = (ROOT / f'examples/{name}/src/lib.rs').read_text()
            actual = set(re.findall(r'#\[plugin_fn\]\s*pub fn (\w+)', source))
            if actual != exports.keys():
                raise ValueError(f'Plugin exports differ from XTP: {name}: {actual ^ exports.keys()}')
        document = dict(schema, exports=exports)
        yield SCHEMA / f"generated/{name}.json", json.dumps(document, indent=2) + '\n'
    # Generate one registration path shared by direct and nested Wasm calls.
    implementations = {}
    for source in (ROOT / 'crates/shared/src').glob('*.rs'):
        text = source.read_text()
        for match in re.finditer(r'host_fn!\(pub (\w+)\(', text):
            name = match.group(1)
            start, end, depth = match.end(), match.end(), 1
            while depth:
                character = text[end]
                depth += (character == '(') - (character == ')')
                end += 1
            arguments = text[start:end - 1].split(';', 1)[1].strip()
            returns = text[end:text.index('{', end)].strip()
            function = schema['imports'][name]
            if bool(arguments) != ('input' in function) or bool(returns) != ('output' in function):
                raise ValueError(f'Host pointer ABI differs from XTP: {name}')
            if name in implementations:
                raise ValueError(f'Duplicate host implementation: {name}')
            implementations[name] = source.stem
    if implementations.keys() != schema['imports'].keys():
        raise ValueError(f'Host implementations differ from XTP: {implementations.keys() ^ schema["imports"].keys()}')
    lines = ['// Generated by scripts/xtp_codegen.py from schema/host.json. Do not edit.',
             "pub fn register<'a>(", "    builder: extism::PluginBuilder<'a>,",
             '    data: extism::UserData<crate::state::State>,',
             ") -> extism::PluginBuilder<'a> {", '    builder']
    for name, function in schema['imports'].items():
        inputs = 'extism::PTR' if 'input' in function else ''
        outputs = 'extism::PTR' if 'output' in function else ''
        implementation = f'crate::{implementations[name]}::{name}'
        compact = f'        .with_function("{name}", [{inputs}], [{outputs}], data.clone(), {implementation})'
        if len(compact) <= 100:
            lines.append(compact)
        else:
            lines.extend(['        .with_function(', f'            "{name}",',
                          f'            [{inputs}],', f'            [{outputs}],',
                          '            data.clone(),', f'            {implementation},', '        )'])
    lines.extend(['}', ''])
    formatted = subprocess.run(['rustfmt', '--edition', '2021', '--emit', 'stdout'],
                               input='\n'.join(lines), text=True, capture_output=True, check=True)
    yield ROOT / 'crates/shared/src/generated/host_functions.rs', formatted.stdout

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generated():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated XTP file: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('XTP PDK imports, plugin schemas, and shared host registrations agree')

if __name__ == '__main__':
    main()
