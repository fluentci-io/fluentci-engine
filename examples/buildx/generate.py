"""Generate typed, named module arguments from a pinned Docker Buildx help snapshot."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SNAPSHOT = HERE / "buildx-options.json"
RESERVED = {"type", "data", "class", "instance", "module", "import", "foreign", "in", "where", "case", "of", "do", "let"}


def camel(value):
    parts = value.split("-")
    result = parts[0] + "".join(part.title() for part in parts[1:])
    return result + "_" if result in RESERVED else result


def command_name(path):
    return "_".join(part.replace("-", "_") for part in path) if path else "buildx"


def pure_name(path):
    return camel("-".join(path)) if path else "buildx"


def capture():
    environment = dict(os.environ, BUILDX_EXPERIMENTAL="1")
    pending = [[]]
    nodes = []
    while pending:
        path = pending.pop(0)
        help_text = subprocess.check_output(["docker", "buildx", *path, "--help"], env=environment, text=True)
        flags, children, section = [], [], ""
        for line in help_text.splitlines():
            if re.match(r"^[A-Za-z][^:]+:$", line):
                section = line
            child = re.match(r"^  ([a-z][a-z0-9-]+)\s{2,}(.+)", line)
            if child and "Commands:" in section:
                children.append(child[1])
            flag = re.match(r"^\s+(?:-\S,\s+)?--([a-z0-9-]+)(?: ([A-Za-z][A-Za-z0-9]*))?\s{2,}(.*)$", line)
            if flag:
                kind = flag[2] or "boolean"
                if kind not in {"boolean", "string", "stringArray", "strings", "filter", "bytes", "duration", "ulimit", "int", "int64"}:
                    raise ValueError(f"Unknown flag type: {kind}")
                flags.append({"flag": flag[1], "type": kind, "description": flag[3]})
        nodes.append({"path": path, "usage": help_text.splitlines()[0], "options": flags, "children": children})
        pending.extend(path + [child] for child in children)
    SNAPSHOT.write_text(json.dumps({"version": subprocess.check_output(["docker", "buildx", "version"], text=True).strip(),
                                    "experimentalIncluded": True, "commands": nodes}, indent=2) + "\n")


def kind_type(kind):
    if kind in {"stringArray", "strings", "filter", "ulimit"}:
        return "Array String", {"type": "array", "items": {"type": "string"}}, "arrayOption"
    if kind == "boolean":
        return "Boolean", {"type": "boolean"}, "booleanOption"
    if kind in {"int", "int64"}:
        return "Int", {"type": "integer"}, "intOption"
    return "String", {"type": "string"}, "stringOption"


def positional(path, children):
    command = command_name(path)
    if children:
        return "arguments", "Array String", [], "positional", "Subcommand positional arguments; prefer the corresponding named export."
    if command in {"build", "dap_build", "debug_build"}:
        return "context", "String", ".", "single", "Build context: path, URL or '-' (stdin is not forwarded by the guest)."
    if command == "bake":
        return "targets", "Array String", [], "positional", "Bake targets."
    if command == "create":
        return "endpoint", "Maybe String", None, "maybe", "Builder context or endpoint."
    if command in {"inspect", "stop"}:
        return "name", "Maybe String", None, "maybe", "Builder instance name."
    if command in {"use", "imagetools_inspect"}:
        return "name", "String", "", "single", "Required builder/image name."
    if command == "rm":
        return "names", "Array String", [], "positional", "Builder instance names."
    if command in {"history_export", "history_rm"}:
        return "refs", "Array String", [], "positional", "Build record references."
    if command in {"history_logs", "history_open", "history_trace"}:
        return "ref", "Maybe String", None, "maybe", "Build record reference."
    if command == "history_inspect_attachment":
        return "references", "Array String", [], "positional", "Optional REF and DIGEST positional arguments."
    if command == "imagetools_create":
        return "sources", "Array String", [], "positional", "Image source references."
    if command == "policy_eval":
        return "source", "String", "", "single", "Required policy evaluation source."
    if command == "policy_test":
        return "path", "String", ".", "single", "Policy test directory."
    if command == "history_import":
        return "arguments", "Array String", [], "positional", "Import positional arguments; use the file option instead of interactive stdin."
    return None


def generated():
    snapshot = json.loads(SNAPSHOT.read_text())
    nodes = snapshot["commands"]
    index = {tuple(node["path"]): node for node in nodes}
    source = ["-- Generated by generate.py. Edit buildx-options.json and regenerate.",
              "module Buildx.Commands where", "", "import Prelude", "import Buildx as B",
              "import Data.Argonaut.Core (Json)", "import Data.Either (Either)",
              "import Data.Maybe (Maybe(..))", "import FluentCI.Host.Plan as Plan", ""]
    main = ["-- Generated by generate.py.", "module Main where", "", "import Prelude",
            "import Buildx as B", "import Buildx.Commands as C", "import Data.Argonaut.Core (Json)",
            "import Data.Argonaut.Parser (jsonParser)", "import Data.Either (Either(..))",
            "import Effect (Effect)", "import Effect.Exception (throw)",
            "import FluentCI.Host.Plan as Plan", "import FluentCI.Plugin as P", "",
            "invoke :: forall a. (Json -> Either String a) -> (a -> Either String Plan.Plan) -> (a -> B.Runtime) -> Effect Unit",
            "invoke decode makePlan runtime = do", "  input <- P.input >>= B.require",
            "  json <- case jsonParser input of", "    Left error -> throw error", "    Right value -> pure value",
            "  arguments <- case decode json of", "    Left error -> throw error", "    Right value -> pure value",
            "  plan <- case makePlan arguments of", "    Left error -> throw error", "    Right value -> pure value",
            "  B.execute (runtime arguments) plan >>= P.output >>= B.require", ""]
    exports = {}
    docs = ["# Buildx module arguments", "", "Generated from the committed option snapshot:",
            "`" + snapshot["version"] + "`. Includes inherited and experimental options.",
            "Option fields are camelCase versions of Docker's long flags; `type` is named",
            "`type_` in PureScript. Missing flags retain Docker defaults, including default-true",
            "booleans. Explicit `false` is emitted as `--flag=false`. Array values repeat the flag.",
            "Docker byte sizes and durations are strings (for example `2g`, `30s`).", ""]
    for node in nodes:
        path = node["path"]
        pure = pure_name(path)
        public = command_name(path)
        title = pure[0].upper() + pure[1:]
        fields = {}
        for depth in range(len(path) + 1):
            for option in index[tuple(path[:depth])]["options"]:
                key = camel(option["flag"])
                if key not in fields:
                    ps, js, emit = kind_type(option["type"])
                    fields[key] = {**option, "ps": ps, "js": js, "emit": emit, "depth": depth}
        fields["help"] = {"flag": "help", "ps": "Boolean", "js": {"type": "boolean"},
                          "emit": "booleanOption", "depth": len(path), "description": "Show this command's help."}
        position = positional(path, node["children"])
        runtime = [("project", "String", '"."'), ("runDir", "String", '""'), ("docker", "String", '"docker"'),
                   ("timeoutMs", "Int", "900000"), ("experimental", "Boolean", "false")]
        definition = [(key, ps) for key, ps, _ in runtime]
        if position:
            definition.append((position[0], position[1]))
        definition.extend((key, "Maybe (" + field["ps"] + ")") for key, field in fields.items())
        source += [f"type {title}Args =", "  { " + "\n  , ".join(key + " :: " + ps for key, ps in definition) + "\n  }", "",
                   f"{pure}Args :: String -> String -> {title}Args", f"{pure}Args project runDir =",
                   '  { project, runDir, docker: "docker", timeoutMs: 900000, experimental: false']
        if position:
            default = "Nothing" if position[1].startswith("Maybe") else json.dumps(position[2])
            source.append(f"  , {position[0]}: {default}")
        source += [f"  , {key}: Nothing" for key in fields]
        source += ["  }", "", f"decode{title}Args :: Json -> Either String {title}Args", f"decode{title}Args json = do",
                   "  object <- B.decodeObject " + json.dumps([key for key, _ in definition]) + " json"]
        local = lambda key: "argument" + key[0].upper() + key[1:]
        for key, _, fallback in runtime:
            source.append(f'  {local(key)} <- B.field object "{key}" {fallback}')
        if position:
            key, ps, default, _, _ = position
            source.append(f'  {local(key)} <- B.optional object "{key}"' if ps.startswith("Maybe") else f'  {local(key)} <- B.field object "{key}" {json.dumps(default)}')
        source += [f'  {local(key)} <- B.optional object "{key}"' for key in fields]
        source += ["  pure { " + ", ".join(key + ": " + local(key) for key, _ in definition) + " }", "",
                   f"runtime{title} :: {title}Args -> B.Runtime", f"runtime{title} arguments =",
                   "  { " + ", ".join(key + ": arguments." + key for key, _, _ in runtime) + " }", "",
                   f"{pure}Arguments :: {title}Args -> Array String", f"{pure}Arguments arguments =", '  [ "buildx" ]']
        for depth in range(len(path) + 1):
            if depth:
                source.append("  <> [ " + json.dumps(path[depth - 1]) + " ]")
            for key, field in fields.items():
                if field["depth"] == depth:
                    source.append(f'  <> B.{field["emit"]} "{field["flag"]}" arguments.{key}')
        if position:
            key, _, _, mode, _ = position
            expression = f'B.maybePositional arguments.{key}' if mode == 'maybe' else f'[ arguments.{key} ]' if mode == 'single' else f'arguments.{key}'
            source.append(f'  <> B.positional ({expression})')
        source += ["", f"{pure} :: {title}Args -> Either String Plan.Plan",
                   f"{pure} arguments = B.commandPlan (runtime{title} arguments) ({pure}Arguments arguments)", ""]
        main += [f"{public} :: Effect Unit", f"{public} = invoke C.decode{title}Args C.{pure} C.runtime{title}", ""]
        properties = {"project": {"type": "string", "default": "."}, "runDir": {"type": "string", "minLength": 1},
                      "docker": {"type": "string", "default": "docker"},
                      "timeoutMs": {"type": "integer", "format": "int32", "minimum": 1, "maximum": 2147483647, "default": 900000},
                      "experimental": {"type": "boolean", "default": False}}
        if position:
            key, ps, default, _, description = position
            properties[key] = {"type": "array", "items": {"type": "string"}} if ps == "Array String" else {"type": "string"}
            properties[key]["description"] = description
            if default is not None:
                properties[key]["default"] = default
        for key, field in fields.items():
            properties[key] = dict(field["js"], description="--" + field["flag"] + ": " + field["description"])
        exports[public] = {"input": {"type": "object", "properties": properties, "required": ["runDir"],
                                     "additionalProperties": False, "contentType": "application/json"},
                           "output": {"type": "string", "contentType": "text/plain; charset=utf-8"}}
        docs += ["## `" + public + "`", "", "`" + node["usage"] + "`", "",
                 f'PureScript: `Buildx.Commands.{pure} :: {title}Args -> Either String Plan.Plan`.', "",
                 "Common module parameters: `project` (default `.`), `runDir` (required, fresh),",
                 "`docker` (executable, default `docker`), `timeoutMs` (default 900000),",
                 "`experimental` (default false, enables `BUILDX_EXPERIMENTAL=1`).", ""]
        if position:
            docs += [f'Positional parameter: `{position[0]} :: {position[1]}` — {position[4]}', ""]
        docs += ["| Module argument | Docker option | Type |", "| --- | --- | --- |"]
        docs += [f'| `{key}` | `--{field["flag"]}` | `{field["ps"]}` |' for key, field in fields.items()]
        docs.append("")
    yield HERE / "src/Buildx/Commands.purs", "\n".join(source)
    yield HERE / "src/Main.purs", "\n".join(main)
    yield HERE / "entry.mjs", 'export { ' + ', '.join(exports) + ' } from "./output/Main/index.js";\n'
    yield HERE / "OPTIONS.md", "\n".join(docs)
    plugins_path = ROOT / "schema/plugins.json"
    plugins = json.loads(plugins_path.read_text())
    plugins["buildx"] = exports
    yield plugins_path, json.dumps(plugins, indent=2) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capture", action="store_true", help="Replace the pinned snapshot using the installed docker buildx CLI (no daemon required)")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    if arguments.capture:
        capture()
    for path, text in generated():
        if arguments.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Stale generated Buildx file: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print("Buildx named argument types, decoders, exports and schemas agree")
